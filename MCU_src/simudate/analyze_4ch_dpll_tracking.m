function result = analyze_4ch_dpll_tracking(config)
%ANALYZE_4CH_DPLL_TRACKING 四路同步采集下的DPLL追踪闭合分析。

addpath(config.simudateDirectory);

pciPath = fullfile(config.dataDirectory, config.pciFileName);
fileInfo = dir(pciPath);
fileSampleCount = (fileInfo.bytes - config.headerBytes) / ...
    (2 * config.channelCount);
sampleCount = min(fileSampleCount, floor(config.processingEndRawSample));
if isfinite(config.processingEndRawSample) && ...
        config.processingEndRawSample > fileSampleCount
    fprintf('配置截止点超过文件总长度，自动按文件末尾%d点处理。\n', ...
        fileSampleCount);
end
tag = string(datetime('now', 'Format', 'yyyyMMdd_HHmmss'));
[~, datasetName] = fileparts(pciPath);
outputDirectory = fullfile(config.outputParentDirectory, ...
    datasetName + "_" + tag);
figureDirectory = fullfile(outputDirectory, "figures");
tableDirectory = fullfile(outputDirectory, "tables");
mkdir(figureDirectory);
mkdir(tableDirectory);

fprintf('\n=== 四通道DPLL追踪分析 ===\n');
fprintf('文件：%s\n', pciPath);
fprintf('每通道点数：%d；时长：%.6f s\n', ...
    sampleCount, sampleCount / config.sampleRateHz);
if sampleCount < fileSampleCount
    fprintf('已按配置截断：文件共%d点，本次只处理1 .. %d。\n', ...
        fileSampleCount, sampleCount);
end
fprintf('结果：%s\n', outputDirectory);

%% CH1：先建立双峰身份，后续只使用主采样峰
fprintf('\n[1/5] 读取CH%d并识别双峰...\n', config.pulseChannel);
pulseVolts = (read_pci_channel(pciPath, config.pulseChannel, ...
    sampleCount, config) - 8192) / 8192;
pulseVolts = pulseVolts - median(pulseVolts);
peaks = locate_double_peaks(pulseVolts, config);
make_peak_identification_figure(pulseVolts, peaks, config, ...
    figureDirectory);
clear pulseVolts

peakTime = (peaks.samplingLocation - 1) / config.sampleRateHz;
interactionTime = (peaks.interactionLocation - 1) / ...
    config.sampleRateHz;
fprintf('双峰周期：%d；两峰平均间隔：%.3f us\n', ...
    numel(peakTime), 1e6 * mean(peakTime - interactionTime));

%% CH4：FPGA定点CIC/DC Block，之后用双精度IQ累积相位
fprintf('\n[2/5] 处理CH%d参考输入...\n', config.referenceChannel);
frontendMat = fullfile(outputDirectory, ...
    datasetName + "_ch" + config.referenceChannel + ...
    "_CIC_DCBlock_3M125.mat");
extract_pci_reference_frontend(pciPath, frontendMat, ...
    dataset_id=datasetName, ...
    frontend_mex_dir=config.frontendMexDirectory, ...
    channel_count=config.channelCount, ...
    channel_index=config.referenceChannel, ...
    maximum_source_samples=sampleCount, ...
    compute_source_sha256=false);
frontend = load(frontendMat, 'frontendOutput', 'metadata');
referenceCic = reference_analysis.estimate_iq_phase( ...
    frontend.frontendOutput, frontend.metadata.outputSampleRate, ...
    observation_rate_hz=config.referenceObservationRateHz, ...
    iq_window_s=config.referenceIqWindowSeconds, ...
    frequency_aperture_s=config.frequencyApertureSeconds);
referenceCic.time_s = referenceCic.time_s - ...
    config.cicGroupDelaySeconds;
clear frontend

referenceRawCodes = read_pci_channel(pciPath, ...
    config.referenceChannel, sampleCount, config);
referenceRaw = reference_analysis.estimate_iq_phase( ...
    referenceRawCodes, config.sampleRateHz, ...
    carrier_frequency_hz=referenceCic.carrier_frequency_hz, ...
    observation_rate_hz=config.referenceObservationRateHz, ...
    iq_window_s=config.referenceIqWindowSeconds, ...
    frequency_aperture_s=config.frequencyApertureSeconds);
clear referenceRawCodes

%% CH2：直接从500倍DDS正弦重建连续相位
fprintf('\n[3/5] 处理CH%d自适应时钟...\n', ...
    config.adaptiveClockChannel);
clockCodes = read_pci_channel(pciPath, ...
    config.adaptiveClockChannel, sampleCount, config);
adaptiveClock = reference_analysis.estimate_iq_phase( ...
    clockCodes, config.sampleRateHz, ...
    observation_rate_hz=config.clockObservationRateHz, ...
    iq_window_s=config.clockIqWindowSeconds, ...
    frequency_aperture_s=config.frequencyApertureSeconds);
clear clockCodes

%% 在同一组主采样峰端点上建立误差恒等式
refPhaseCic = interp1(referenceCic.time_s, ...
    referenceCic.phase_cycles, peakTime, 'pchip');
refPhaseRaw = interp1(referenceRaw.time_s, ...
    referenceRaw.phase_cycles, peakTime, 'pchip');
clockPhase = interp1(adaptiveClock.time_s, ...
    adaptiveClock.phase_cycles, peakTime, 'pchip');
referenceCrossingTime = (referenceCic.crossing_index - 1) / ...
    referenceCic.sample_rate_hz - config.cicGroupDelaySeconds;
referencePhaseCrossing = phase_from_crossings(referenceCrossingTime, ...
    referenceCic.crossing_cycle, peakTime, ...
    config.referenceIqWindowSeconds);
clockCrossingTime = (adaptiveClock.crossing_index - 1) / ...
    adaptiveClock.sample_rate_hz;
clockPhaseCrossing = phase_from_crossings(clockCrossingTime, ...
    adaptiveClock.crossing_cycle, peakTime, config.clockIqWindowSeconds);

interval.startTime_s = peakTime(1:end - 1);
interval.endTime_s = peakTime(2:end);
interval.midTime_s = 0.5 * (interval.startTime_s + ...
    interval.endTime_s);
interval.pulseSpacing_62M5 = diff(peaks.samplingLocation);
interval.pulseDuration_s = diff(peakTime);
interval.pulseEquivalentFrequency_Hz = ...
    config.referenceCyclesPerPulse ./ interval.pulseDuration_s;
interval.referenceCyclesCic = diff(refPhaseCic);
interval.referenceCyclesRaw = diff(refPhaseRaw);
interval.referenceCyclesCicCrossing = diff(referencePhaseCrossing);
interval.clockCycles500 = diff(clockPhase);
interval.clockCycles500Crossing = diff(clockPhaseCrossing);
interval.referenceAverageFrequencyCic_Hz = ...
    interval.referenceCyclesCic ./ interval.pulseDuration_s;
interval.referenceAverageFrequencyRaw_Hz = ...
    interval.referenceCyclesRaw ./ interval.pulseDuration_s;
interval.clockEquivalentFrequency_Hz = interval.clockCycles500 ./ ...
    (config.capturedClockMultiplier * interval.pulseDuration_s);
interval.referencePulseFrequencyMismatch_Hz = ...
    interval.referenceAverageFrequencyCic_Hz - ...
    interval.pulseEquivalentFrequency_Hz;
interval.clockReferenceFrequencyMismatch_Hz = ...
    interval.clockEquivalentFrequency_Hz - ...
    interval.referenceAverageFrequencyCic_Hz;

M = config.capturedClockMultiplier;
R = config.referenceCyclesPerPulse;
interval.finalError500 = interval.clockCycles500 - M * R;
interval.referenceEvent500 = M * (interval.referenceCyclesCic - R);
interval.pllTracking500 = interval.clockCycles500 - ...
    M * interval.referenceCyclesCic;
interval.closure500 = interval.finalError500 - ...
    interval.referenceEvent500 - interval.pllTracking500;
interval.finalError500Crossing = interval.clockCycles500Crossing - M * R;
interval.referenceEvent500Crossing = M * ...
    (interval.referenceCyclesCicCrossing - R);
interval.pllTracking500Crossing = interval.clockCycles500Crossing - ...
    M * interval.referenceCyclesCicCrossing;
interval.closure500Crossing = interval.finalError500Crossing - ...
    interval.referenceEvent500Crossing - interval.pllTracking500Crossing;

% 四种相位测量组合。第一个后缀是CH2，第二个后缀是CH4。
interval.pllTracking500Ch2IqCh4Iq = interval.pllTracking500;
interval.pllTracking500Ch2IqCh4Crossing = interval.clockCycles500 - ...
    M * interval.referenceCyclesCicCrossing;
interval.pllTracking500Ch2CrossingCh4Iq = ...
    interval.clockCycles500Crossing - M * interval.referenceCyclesCic;
interval.pllTracking500Ch2CrossingCh4Crossing = ...
    interval.pllTracking500Crossing;

scaleToReport = config.reportClockMultiplier / M;
interval.finalError2000 = scaleToReport * interval.finalError500;
interval.referenceEvent2000 = scaleToReport * ...
    interval.referenceEvent500;
interval.pllTracking2000 = scaleToReport * interval.pllTracking500;
interval.closure2000 = scaleToReport * interval.closure500;
interval.finalError2000Crossing = scaleToReport * ...
    interval.finalError500Crossing;
interval.referenceEvent2000Crossing = scaleToReport * ...
    interval.referenceEvent500Crossing;
interval.pllTracking2000Crossing = scaleToReport * ...
    interval.pllTracking500Crossing;
interval.closure2000Crossing = scaleToReport * ...
    interval.closure500Crossing;
interval.pllTracking2000Ch2IqCh4Iq = scaleToReport * ...
    interval.pllTracking500Ch2IqCh4Iq;
interval.pllTracking2000Ch2IqCh4Crossing = scaleToReport * ...
    interval.pllTracking500Ch2IqCh4Crossing;
interval.pllTracking2000Ch2CrossingCh4Iq = scaleToReport * ...
    interval.pllTracking500Ch2CrossingCh4Iq;
interval.pllTracking2000Ch2CrossingCh4Crossing = scaleToReport * ...
    interval.pllTracking500Ch2CrossingCh4Crossing;
interval.ch2IqToCrossingEffect2000 = ...
    interval.pllTracking2000Ch2CrossingCh4Iq - ...
    interval.pllTracking2000Ch2IqCh4Iq;
interval.ch4IqToCrossingEffect2000 = ...
    interval.pllTracking2000Ch2IqCh4Crossing - ...
    interval.pllTracking2000Ch2IqCh4Iq;
interval.iqCrossingCombinationClosure2000 = ...
    interval.pllTracking2000Ch2CrossingCh4Crossing - ...
    interval.pllTracking2000Ch2IqCh4Iq - ...
    interval.ch2IqToCrossingEffect2000 - ...
    interval.ch4IqToCrossingEffect2000;
cyclesToMrad = 2 * pi * 1000 / config.reportClockMultiplier;
interval.finalErrorMrad = cyclesToMrad * interval.finalError2000;
interval.referenceEventMrad = cyclesToMrad * ...
    interval.referenceEvent2000;
interval.pllTrackingMrad = cyclesToMrad * interval.pllTracking2000;

%% CH2/CH4载波只用于判断PCI固定时间轴是否连续
continuity = classify_capture_continuity(peaks.samplingLocation, ...
    referenceCic, adaptiveClock, config);
interval.pulseSpacingOutlier = continuity.pulseSpacingOutlier;
interval.containsClockCrossingOutlier = ...
    continuity.containsClockCrossingOutlier;
interval.containsReferenceCrossingOutlier = ...
    continuity.containsReferenceCrossingOutlier;
interval.containsCarrierDiscontinuity = ...
    continuity.containsCarrierDiscontinuity;
interval.pulseOnlyMissingCandidate = ...
    continuity.pulseOnlyMissingCandidate;
interval.validForTrackingAnalysis = ...
    continuity.validForTrackingAnalysis;
interval.maximumClockCrossingDeviationSamples = ...
    continuity.maximumClockCrossingDeviationSamples;
interval.maximumReferenceCrossingDeviationSamples = ...
    continuity.maximumReferenceCrossingDeviationSamples;

%% CH3：用端点相位差独立预测PLL自身项
fprintf('\n[4/5] 处理CH%d相位残差并扫描固定通道延时...\n', ...
    config.phaseResidualChannel);
phaseVolts = (read_pci_channel(pciPath, ...
    config.phaseResidualChannel, sampleCount, config) - 8192) / 8192;
phaseRadians = config.phaseRadiansPerVolt * phaseVolts;
delaySamples = (-round(config.phaseDelayScanHalfSeconds * ...
    config.sampleRateHz):config.phaseDelayScanStepSamples: ...
    round(config.phaseDelayScanHalfSeconds * config.sampleRateHz)).';
delayCorrelation = zeros(size(delaySamples));
for k = 1:numel(delaySamples)
    phaseAtPeak = mean_at_locations(phaseRadians, ...
        peaks.samplingLocation + delaySamples(k), ...
        config.phaseAverageHalfSamples);
    prediction = phase_prediction(diff(phaseAtPeak), ...
        config.capturedClockMultiplier, config.phasePredictionSign);
    use = interval.validForTrackingAnalysis;
    delayCorrelation(k) = correlation(prediction(use), ...
        interval.pllTracking500(use));
end
[~, bestDelayIndex] = max(delayCorrelation);
bestDelaySamples = delaySamples(bestDelayIndex);
phaseAtPeakZero = mean_at_locations(phaseRadians, ...
    peaks.samplingLocation, config.phaseAverageHalfSamples);
phaseAtPeakBest = mean_at_locations(phaseRadians, ...
    peaks.samplingLocation + bestDelaySamples, ...
    config.phaseAverageHalfSamples);
interval.phasePrediction500Zero = phase_prediction( ...
    diff(phaseAtPeakZero), M, config.phasePredictionSign);
interval.phasePrediction500Best = phase_prediction( ...
    diff(phaseAtPeakBest), M, config.phasePredictionSign);
interval.phasePrediction2000Best = scaleToReport * ...
    interval.phasePrediction500Best;

%% 一个完整脉冲周期宽度的滑动累计
windowSeconds = median(interval.pulseDuration_s);
slideTime = referenceCic.time_s(referenceCic.time_s >= ...
    peakTime(1) + windowSeconds & referenceCic.time_s <= peakTime(end));
referenceNow = interp1(referenceCic.time_s, ...
    referenceCic.phase_cycles, slideTime, 'pchip');
referencePast = interp1(referenceCic.time_s, ...
    referenceCic.phase_cycles, slideTime - windowSeconds, 'pchip');
rawNow = interp1(referenceRaw.time_s, referenceRaw.phase_cycles, ...
    slideTime, 'pchip');
rawPast = interp1(referenceRaw.time_s, referenceRaw.phase_cycles, ...
    slideTime - windowSeconds, 'pchip');
clockNow = interp1(adaptiveClock.time_s, ...
    adaptiveClock.phase_cycles, slideTime, 'pchip');
clockPast = interp1(adaptiveClock.time_s, ...
    adaptiveClock.phase_cycles, slideTime - windowSeconds, 'pchip');

sliding.time_s = slideTime;
sliding.referenceFrequencyCic_Hz = ...
    (referenceNow - referencePast) / windowSeconds;
sliding.referenceFrequencyRaw_Hz = ...
    (rawNow - rawPast) / windowSeconds;
sliding.clockEquivalentFrequency_Hz = ...
    (clockNow - clockPast) / (M * windowSeconds);
sliding.pulseEquivalentFrequency_Hz = interp1(interval.midTime_s, ...
    interval.pulseEquivalentFrequency_Hz, slideTime, 'linear', 'extrap');
sliding.phaseResidualMrad = 1000 * mean_at_locations(phaseRadians, ...
    1 + slideTime * config.sampleRateHz, ...
    config.phaseAverageHalfSamples);
clear phaseRadians phaseVolts

%% 表格、指标和图
fprintf('\n[5/5] 计算指标并保存图表...\n');
intervalTable = build_interval_table(interval, peaks, ...
    phaseAtPeakZero, phaseAtPeakBest);
slidingTable = struct2table(sliding);
delayTable = table(delaySamples, 1e6 * delaySamples / ...
    config.sampleRateHz, delayCorrelation, ...
    'VariableNames', {'delay_samples', 'delay_us', 'correlation'});
segmentTable = build_segment_table(interval);

summary = build_summary(config, referenceCic, referenceRaw, ...
    adaptiveClock, interval, bestDelaySamples, delayCorrelation(bestDelayIndex));
summary.samplingPeakCorrelationMedian = median(peaks.samplingCorrelation);
summary.samplingPeakCorrelationMinimum = min(peaks.samplingCorrelation);
summary.interactionPeakCorrelationMedian = median(peaks.interactionCorrelation);
summary.interactionPeakCorrelationMinimum = min(peaks.interactionCorrelation);
summaryTable = summary_to_table(summary);

writetable(intervalTable, fullfile(tableDirectory, ...
    'interval_metrics.csv'));
writetable(slidingTable, fullfile(tableDirectory, ...
    'sliding_one_pulse_window.csv'));
writetable(delayTable, fullfile(tableDirectory, ...
    'phase_delay_scan.csv'));
writetable(segmentTable, fullfile(tableDirectory, ...
    'segment_metrics.csv'));
writetable(summaryTable, fullfile(tableDirectory, ...
    'summary_metrics.csv'));
writetable(continuity.summaryTable, fullfile(tableDirectory, ...
    'capture_continuity_summary.csv'));
writetable(continuity.clockCrossingOutlierTable, ...
    fullfile(tableDirectory, 'ch2_crossing_outliers.csv'));
writetable(continuity.referenceCrossingOutlierTable, ...
    fullfile(tableDirectory, 'ch4_cic_crossing_outliers.csv'));

make_overview_figure(interval, phaseAtPeakBest, config, figureDirectory);
make_sliding_figure(sliding, config, figureDirectory);
make_reference_crosscheck_figure(interval, sliding, config, ...
    figureDirectory);
make_decomposition_figure(interval, config, figureDirectory);
make_phase_validation_figure(interval, phaseAtPeakBest, ...
    delayTable, bestDelaySamples, config, figureDirectory);
make_peak_reference_pll_relation_figure(interval, config, figureDirectory);
make_capture_continuity_figure(interval, continuity, config, ...
    figureDirectory);

result.schemaVersion = 1;
result.createdAt = char(datetime('now', ...
    'Format', 'yyyy-MM-dd HH:mm:ss Z'));
result.pciPath = char(pciPath);
result.outputDirectory = char(outputDirectory);
result.config = config;
result.peaks = peaks;
result.referenceCic = compact_phase(referenceCic);
result.referenceRaw = compact_phase(referenceRaw);
result.adaptiveClock = compact_phase(adaptiveClock);
result.interval = interval;
result.sliding = sliding;
result.phaseAtPeakZero_rad = phaseAtPeakZero;
result.phaseAtPeakBest_rad = phaseAtPeakBest;
result.phaseDelayScan = delayTable;
result.captureContinuity = continuity;
result.summary = summary;
result.posteriorPeakDataUsedForController = false;
result.phaseDelayScanPosteriorDiagnosticOnly = true;
save(fullfile(outputDirectory, 'four_channel_tracking_analysis.mat'), ...
    'result', '-v7.3');

fprintf('\n=== 主要结果 ===\n');
fprintf('CH4参考频率：%.6f Hz\n', referenceCic.carrier_frequency_hz);
fprintf('CH2时钟频率：%.6f Hz；倍频比：%.9f\n', ...
    adaptiveClock.carrier_frequency_hz, ...
    adaptiveClock.carrier_frequency_hz / referenceCic.carrier_frequency_hz);
fprintf('2000倍等效最终/reference-event/PLL RMS：%.6f / %.6f / %.6f cycles\n', ...
    summary.finalRms2000, summary.referenceEventRms2000, ...
    summary.pllTrackingRms2000);
fprintf(['时间轴连续且峰间距正常%d段：最终/reference-event/PLL RMS ' ...
    '%.6f / %.6f / %.6f cycles\n'], ...
    summary.validIntervalCount, summary.validFinalRms2000, ...
    summary.validReferenceEventRms2000, summary.validPllTrackingRms2000);
fprintf(['采集载波断点%d段；仅CH1缺脉冲候选%d段；' ...
    '全部原样保留在MAT/CSV中\n'], ...
    summary.carrierDiscontinuityIntervalCount, ...
    summary.pulseOnlyMissingCandidateCount);
fprintf('正过零交叉核验最终/reference-event/PLL RMS：%.6f / %.6f / %.6f cycles\n', ...
    summary.finalRms2000Crossing, ...
    summary.referenceEventRms2000Crossing, ...
    summary.pllTrackingRms2000Crossing);
fprintf('闭合残差最大值：%.3e cycles\n', ...
    summary.closurePeak2000);
fprintf('IQ/亚采样正过零交叉差异：CH4 %.6f；CH2 %.6f cycles RMS\n', ...
