function audit = crossing_continuity_audit(crossingIndex, scale, ...
    delaySamples, minimumDeviation, madMultiplier)
probeCount = min(numel(crossingIndex), 1e6);
probeSpacing = scale * diff(crossingIndex(1:probeCount));
spacingMedian = median(probeSpacing);
spacingMad = median(abs(probeSpacing - spacingMedian));
outlierThreshold = max(minimumDeviation, ...
    madMultiplier * 1.4826 * spacingMad);

outlierLocation = zeros(0, 1);
outlierSpacing = zeros(0, 1);
chunkCrossings = 5e6;
first = 1;
while first < numel(crossingIndex)
    last = min(first + chunkCrossings, numel(crossingIndex));
    crossing = crossingIndex(first:last);
    spacing = scale * diff(crossing);
    deviation = spacing - spacingMedian;
    use = abs(deviation) >= outlierThreshold;
    midpoint = 1 + (0.5 * (crossing(1:end - 1) + ...
        crossing(2:end)) - 1) * scale - delaySamples;
    outlierLocation = [outlierLocation; midpoint(use)]; %#ok<AGROW>
    outlierSpacing = [outlierSpacing; spacing(use)]; %#ok<AGROW>
    first = last;
end

audit.crossingCount = numel(crossingIndex);
audit.spacingMedian = spacingMedian;
audit.spacingMad = spacingMad;
audit.outlierThreshold = outlierThreshold;
audit.outlierCount = numel(outlierLocation);
audit.outlierLocation = outlierLocation;
audit.outlierSpacing = outlierSpacing;
audit.outlierDeviation = outlierSpacing - spacingMedian;
end

function [containsOutlier, maximumDeviation] = map_crossing_outliers( ...
    peakLocation, outlierLocation, outlierDeviation)
intervalCount = numel(peakLocation) - 1;
bin = discretize(outlierLocation, peakLocation);
inside = isfinite(bin);
containsOutlier = accumarray(bin(inside), true(nnz(inside), 1), ...
    [intervalCount 1], @any, false);
maximumDeviation = accumarray(bin(inside), ...
    abs(outlierDeviation(inside)), [intervalCount 1], @max, 0);
end

function value = correlation(a, b)
matrix = corrcoef(a(:), b(:));
value = matrix(1, 2);
end

