function value = rms0(values)
value = sqrt(mean(values(:).^2));
end

function value = cycles_to_mrad(cycles, config)
value = 2 * pi * 1000 / config.reportClockMultiplier * cycles;
end

function apply_display_range(fig, config)
apply_display_range_to_axes(findall(fig, 'Type', 'axes'), config);
end

function apply_display_range_to_axes(axesValue, config)
startMs = 1e3 * (config.displayStartRawSample - 1) / ...
    config.sampleRateHz;
endMs = 1e3 * (config.displayEndRawSample - 1) / ...
    config.sampleRateHz;
for k = 1:numel(axesValue)
    current = xlim(axesValue(k));
    first = max(current(1), startMs);
    last = current(2);
    if isfinite(endMs), last = min(last, endMs); end
    xlim(axesValue(k), [first last]);
end
end

