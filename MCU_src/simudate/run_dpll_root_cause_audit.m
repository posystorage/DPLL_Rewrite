fprintf(file_id, '## Engineering conclusion\n\n');
fprintf(file_id, ['The current P-shift-9 loop tracks the phase presented by ' ...
    'the detector to about one output cycle. Independent zero-crossing, ' ...
    'local-sinusoid, and analytic phase estimators reproduce the large real ' ...
    'peak/reference residual, so the CIC/IIR/CORDIC detector is not its ' ...
    'dominant source. Constant-delay correction is ineffective. The saved ' ...
    'peak file contains integer-valued distances, and the extraction source ' ...
    'rounds locations then selects an integer xcorr lag without sub-sample ' ...
    'interpolation. The IIR contributes about 238 us of group delay, but ' ...
    'constant-delay correction removes only a small fraction of the real ' ...
    'residual. Therefore this dataset cannot support attributing the ' ...
    'remaining fast residual to PI bandwidth or claiming sub-sample peak ' ...
    'ground truth.\n']);
end
