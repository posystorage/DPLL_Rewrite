    '(cycles) | Corr. with PLL |\n']);
fprintf(file_id, '|---|---:|---:|---:|---:|\n');
for k = 1:height(audit.method_metrics)
    row = audit.method_metrics(k, :);
    fprintf(file_id, '| %s | %.6f | %.6f | %.6f | %.6f |\n', ...
        strrep(row.method, '_', ' '), row.rms_cycles, row.std_cycles, ...
        row.fast_std_cycles, row.correlation_with_pll_residual);
end
fprintf(file_id, '\nAll covered intervals contain exactly **113** positive ');
fprintf(file_id, 'reference crossings: **%s**.\n\n', ...
    string(audit.decision.every_interval_contains_113_cycles));
fprintf(file_id, '## Known-truth calibration\n\n');
fprintf(file_id, ['| Method | Phase error RMS (output cycles) |\n' ...
    '|---|---:|\n']);
for k = 1:height(audit.calibration.accuracy)
    fprintf(file_id, '| %s | %.6f |\n', ...
        strrep(audit.calibration.accuracy.method(k), '_', ' '), ...
        audit.calibration.accuracy.phase_error_rms_output_cycles(k));
