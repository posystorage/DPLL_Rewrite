function files = make_timing_figure(audit, figure_dir, visibility)
fig = figure('Visible', visibility, 'Color', 'w', ...
    'Name', 'Timing and peak-resolution audit');
layout = tiledlayout(fig, 3, 1, 'TileSpacing', 'compact', ...
    'Padding', 'compact');
title(layout, 'Fixed-delay scan and integer-lag peak-position signature');
nexttile; hold on;
methods = unique(audit.delay_scan.method, 'stable');
colors = lines(max(numel(methods), numel(audit.method_names)));
for k = 1:numel(methods)
    use = audit.delay_scan.method == methods(k);
    plot(1e3 * audit.delay_scan.shift_s(use), ...
        audit.delay_scan.std_cycles(use), 'LineWidth', 1.0, ...
        'Color', colors(k, :), ...
        'DisplayName', strrep(methods(k), '_', ' '));
end
xlabel('Reference time shift (ms)'); ylabel('Residual std (cycles)');
grid on; legend('Location', 'best');

nexttile; hold on;
for k = 1:numel(audit.method_names)
    phase_fraction = mod(audit.method_phase_at_peak_cycles{k}, 1);
    phase_fraction = unwrap(2 * pi * phase_fraction) / (2 * pi);
    phase_fraction = phase_fraction - mean(phase_fraction);
    plot(audit.validation.peak_time_s, ...
        audit.config.pulse.output_multiplier * phase_fraction, ...
        'Color', colors(k, :), ...
        'DisplayName', strrep(audit.method_names(k), '_', ' '));
end
ylabel('Reference phase at peak (output cycles)');
grid on; legend('Location', 'best');

nexttile;
zero = audit.interval_errors{1};
autocorrelation = nan(12, 1);
for lag = 1:12
    autocorrelation(lag) = corr(zero(1:end-lag), zero(1+lag:end));
end
stem(1:12, autocorrelation, 'filled');
yline(0, '--k'); xlabel('Lag (pulses)');
ylabel('Zero-crossing error autocorrelation'); grid on;
files = dpll.export_paper_figure(fig, ...
    fullfile(figure_dir, 'timing_and_peak_resolution_audit'), [7.2 7.4]);
if strcmp(visibility, 'off'), close(fig); end
end

