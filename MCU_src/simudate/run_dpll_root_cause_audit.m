fprintf(file_id, '\n## Peak extraction evidence\n\n');
for k = 1:height(audit.extractor_audit)
    fprintf(file_id, '- %s: **%s**. %s\n', ...
        audit.extractor_audit.check(k), ...
        string(audit.extractor_audit.result(k)), ...
        audit.extractor_audit.evidence(k));
end
fprintf(file_id, '\n## Error budget\n\n');
fprintf(file_id, '- Real PLL residual: **%.6f cycles RMS**.\n', ...
    sqrt(mean(audit.validation.recovered_interval_error.^2)));
fprintf(file_id, ['- Direct zero-cross reference/peak residual: ' ...
    '**%.6f cycles RMS**.\n'], ...
    metric_value(audit.method_metrics, "zero_crossing", 'rms_cycles'));
fprintf(file_id, ['- FPGA reconstructed reference/peak residual: ' ...
    '**%.6f cycles RMS**.\n'], ...
    metric_value(audit.method_metrics, ...
    "fpga_detector_reconstruction", 'rms_cycles'));
fprintf(file_id, ['- PLL minus detector-observable reference: ' ...
    '**%.6f cycles RMS**.\n'], ...
    sqrt(mean(audit.reference_ceiling.real.pll_minus_reference_error.^2)));
fprintf(file_id, ['- Exact-113 synthetic event PLL residual: ' ...
    '**%.6f cycles RMS**.\n\n'], ...
    sqrt(mean(audit.reference_ceiling.synthetic.pll_residual_error.^2)));
