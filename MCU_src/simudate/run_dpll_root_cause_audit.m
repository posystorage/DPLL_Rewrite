    fprintf(file_id, '| %s | %.6f | %.6f |\n', ...
        strrep(audit.detector_group_delay.method(k), '_', ' '), ...
        audit.detector_group_delay.fitted_group_delay_us(k), ...
        audit.detector_group_delay.gain_span_db(k));
