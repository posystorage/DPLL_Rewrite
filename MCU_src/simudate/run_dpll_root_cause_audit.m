    fprintf(file_id, '- Selected candidate: **%s**.\n', ...
        audit.pi_refinement.selected_candidate.id);
    fprintf(file_id, '- Selected exact-113 RMS: **%.6f cycles**.\n', ...
        audit.pi_refinement.metrics.exact113_rms_cycles(selected_row));
