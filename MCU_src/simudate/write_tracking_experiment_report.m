function report_path = write_tracking_experiment_report( ...
    cic_experiment, fm_experiment, output_dir)
%WRITE_TRACKING_EXPERIMENT_REPORT Write a concise reproducibility report.

report_path = fullfile(output_dir, 'experiment_report.md');
file_id = fopen(report_path, 'w', 'n', 'UTF-8');
if file_id < 0
    error('dpll:ReportOpenFailed', 'Could not create report: %s', report_path);
end
cleanup = onCleanup(@() fclose(file_id));

fprintf(file_id, '# DPLL detector scaling and FM response\n\n');
fprintf(file_id, 'Generated: %s\n\n', ...
    char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss Z')));
fprintf(file_id, 'No pulse-position posterior data was loaded by either experiment. ');
fprintf(file_id, ['The real-data scan uses only the 3.125 MHz FPGA-equivalent ' ...
    'reference waveform.\n\n']);

fprintf(file_id, '## Source provenance\n\n');
fprintf(file_id, '- File: `%s`\n', cic_experiment.provenance.source_file);
fprintf(file_id, '- SHA-256: `%s`\n', cic_experiment.provenance.source_sha256);
fprintf(file_id, '- Bytes: %.0f\n', cic_experiment.provenance.source_bytes);
fprintf(file_id, '- Input range: [%g, %g] at %.0f Hz\n\n', ...
    cic_experiment.provenance.input_sample_range(1), ...
    cic_experiment.provenance.input_sample_range(2), ...
    cic_experiment.provenance.input_sample_rate_hz);

fprintf(file_id, '## CIC output-shift scan\n\n');
fprintf(file_id, ['`output_shift` is the rounding shift immediately before ' ...
    'the signed 20-bit post-IQ CIC output. One added bit halves I and Q.\n\n']);
fprintf(file_id, '| Shift | CIC saturation | CORDIC range | I/Q p99 | Phase RMS (rad) | FLL RMS (Hz) |\n');
fprintf(file_id, '|---:|---:|---:|---:|---:|---:|\n');
metrics = cic_experiment.metrics;
for k = 1:height(metrics)
    fprintf(file_id, '| %d | %.6g | %.6g | %.1f | %.6g | %.6g |\n', ...
        metrics.output_shift(k), metrics.cic_saturation_rate(k), ...
        metrics.cordic_out_of_range_rate(k), ...
        metrics.iq_component_p99_codes(k), metrics.phase_rms_rad(k), ...
        metrics.freq_error_rms_hz(k));
end
fprintf(file_id, '\nRecommended detector shift by the frozen rule: **%d**.\n\n', ...
    cic_experiment.recommended_shift);

fprintf(file_id, '## Fixed-frequency sinusoidal FM response\n\n');
fprintf(file_id, ['The injected phase is `beta*sin(2*pi*fm*t)`. Beta is ' ...
    'constant across points, so frequency-deviation amplitude is `beta*fm`. ' ...
    'Gain and phase come from a least-squares sine/cosine fit after the ' ...
    'configured settling interval.\n\n']);
fprintf(file_id, '| fm (Hz) | df (Hz) | Tracking gain (dB) | Phase (deg) | Frequency residual (dB) | Phase residual (dB) | R2 |\n');
fprintf(file_id, '|---:|---:|---:|---:|---:|---:|---:|\n');
response = fm_experiment.response;
for k = 1:height(response)
    fprintf(file_id, '| %.6g | %.6g | %.4f | %.3f | %.4f | %.4f | %.5f |\n', ...
        response.modulation_frequency_hz(k), ...
        response.frequency_deviation_hz(k), ...
        response.closed_loop_gain_db(k), ...
        response.closed_loop_phase_deg(k), ...
        response.frequency_residual_gain_db(k), ...
        response.phase_residual_gain_db(k), ...
        response.output_fit_r_squared(k));
end
if isfinite(fm_experiment.estimated_minus3db_bandwidth_hz)
    fprintf(file_id, '\nEstimated -3 dB tracking bandwidth: **%.6g Hz**.\n\n', ...
        fm_experiment.estimated_minus3db_bandwidth_hz);
else
    fprintf(file_id, ['\nThe tracking response does not cross -3 dB within ' ...
        'the measured range. This is not evidence of useful bandwidth: ' ...
        'gain peaking and low single-tone fit quality must be checked.\n\n']);
end
low_fit = response.output_fit_r_squared < 0.90;
if any(low_fit)
    fprintf(file_id, ['Points with output-fit R2 below 0.90: **%s Hz**. ' ...
        'At these points the output is not a clean sinusoid, so the reported ' ...
        'gain and phase describe only the fundamental component and must not ' ...
        'be interpreted as an ordinary linear Bode response.\n\n'], ...
        strjoin(compose('%g', response.modulation_frequency_hz(low_fit)), ', '));
end

fprintf(file_id, '## Frozen outputs\n\n');
fprintf(file_id, ['- `cic_scan/raw`: complete fixed-point real-data replays ' ...
    'for every CIC shift.\n']);
fprintf(file_id, ['- `fm_sweep/raw`: synthetic input codes, truth, complete ' ...
    'fixed-point replay, fit window, and phasor fit for every frequency.\n']);
fprintf(file_id, '- CSV files: paper-table source values.\n');
fprintf(file_id, '- Figure folders: 600 dpi PNG, vector PDF/SVG, and MATLAB FIG.\n');
end
